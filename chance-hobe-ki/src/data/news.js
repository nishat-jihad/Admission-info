export function getAllNews() {
  return [...news].sort((a, b) => b.date.localeCompare(a.date));
}

export function getLatestNews(count = NEW_TAG_COUNT) {
  return getAllNews().slice(0, count);
}

export function isNewNews(slug) {
  return getAllNews()
    .slice(0, NEW_TAG_COUNT)
    .some((n) => n.slug === slug);
}

export function getNewsMeta(slug) {
  return news.find((n) => n.slug === slug) || null;
}

// সাইডবার/নিচের "আরও নিউজ" — বর্তমান নিউজ বাদে সর্বশেষগুলো।
export function getMoreNews(slug, count = 5) {
  return getAllNews()
    .filter((n) => n.slug !== slug)
    .slice(0, count);
}

const BN_DIGITS = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];
const BN_MONTHS = [
  "জানুয়ারি",
  "ফেব্রুয়ারি",
  "মার্চ",
  "এপ্রিল",
  "মে",
  "জুন",
  "জুলাই",
  "আগস্ট",
  "সেপ্টেম্বর",
  "অক্টোবর",
  "নভেম্বর",
  "ডিসেম্বর",
];

export function toBn(value) {
  return String(value).replace(/\d/g, (d) => BN_DIGITS[Number(d)]);
}

// "2026-11-05" -> "৫ নভেম্বর ২০২৬"
export function formatBnDate(iso) {
  const [y, m, d] = iso.split("-").map(Number);
  return `${toBn(d)} ${BN_MONTHS[m - 1]} ${toBn(y)}`;
}
