// টেবিলে পরপর একই লেখা থাকলে বারবার না লিখে একটা ঘরে (rowSpan) দেখানোর হিসাব।
// extraTables-এর রো দিয়ে এটা চলে; ইউনিভার্সিটি পেজ ও /updates দুই জায়গাতেই ব্যবহার হয়।
//   • প্রথম কলামে পরপর একই লেখা = একটা গ্রুপ; ঘরটা একবারই দেখায়।
//   • অন্য কলামে পরপর একই লেখা একই গ্রুপের ভেতরে হলে মেলানো হয় (গ্রুপ পেরিয়ে কখনো নয়)।
//   • শুধু সংখ্যার ঘর (আসন "৫০", কোটা "১%") আর খালি ঘর মেলানো হয় না।
//   • কিছু মিললে সারির রং (সাদা/ধূসর) গ্রুপ ধরে বদলায়, নইলে আগের মতো সারি ধরে।
// ফেরত: [{ stripe: "row-white" | "row-grey", cells: [{ cell, span }] }]; span 0 = ঘরটা আঁকা হবে না।
const NUMBER_ONLY = /^[\d\u09E6-\u09EF.,%\s]+$/;
export function mergeTableRows(rows = []) {
  const n = rows.length;
  const cols = rows.reduce((m, r) => Math.max(m, r.length), 0);
  const text = (r, c) => String(rows[r][c] ?? "").trim();
  const group = [];
  let g = -1;
  for (let r = 0; r < n; r++) {
    if (!(r > 0 && text(r, 0) !== "" && rows[r][0] === rows[r - 1][0])) g++;
    group.push(g);
  }
  const span = rows.map((row) => row.map(() => 1));
  for (let c = 0; c < cols; c++) {
    let r = 0;
    while (r < n) {
      let k = r + 1;
      const t = text(r, c);
      if (t !== "" && !NUMBER_ONLY.test(t)) {
        while (k < n && rows[k][c] === rows[r][c] && group[k] === group[r]) k++;
      }
      if (c < rows[r].length) span[r][c] = k - r;
      for (let i = r + 1; i < k; i++) if (c < rows[i].length) span[i][c] = 0;
      r = k;
    }
  }
  const grouped = n > 0 && group[n - 1] < n - 1;
  return rows.map((row, ri) => ({
    stripe: (grouped ? group[ri] : ri) % 2 === 0 ? "row-white" : "row-grey",
    cells: row.map((cell, ci) => ({ cell, span: span[ri][ci] })),
  }));
}
