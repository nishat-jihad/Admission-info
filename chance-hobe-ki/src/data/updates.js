// is added to the table (on /updates and on the university detail page).
// An update can set `extraTables` ([{ title, headers, rows }]) for extra
// tables such as fees / admit-card dates, and `notes` (array of strings)
// for a "গুরুত্বপূর্ণ তথ্য" bullet list. Both render inside the card (UpdatesFilterList.js) and the university detail page.
// An extraTables entry can set `detailOnly: true` — it then shows only on the
// university detail page, not on the /updates card (for long reference tables).
// An update can set `foldExtraTables: true` — then every extraTable (even the first)
// starts folded on /updates; only the schedule table stays open. Click the title to open.
// An update can set `foldNotes: true` — then the "গুরুত্বপূর্ণ তথ্য" list starts folded on /updates and on the university detail page; click the title to open.
// An update can set `sourcePdf` (path under /public) to show a button that
// opens the original circular PDF in a new tab.
// An update can set `sourcePdfs` ([{ label, href }]) to show more than one
